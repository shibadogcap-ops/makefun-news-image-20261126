# ---------------------------------------------------------------------------
# Metrics
# ---------------------------------------------------------------------------

def text_width(s, scale):
    """Pixel width of `s` at `scale`: len(s)*6*scale - scale (0 if empty)."""
    if not s:
        return 0
    return len(s) * 6 * scale - scale


def _draw_glyph(cv, glyph, x, y, color, scale):
    for row, line in enumerate(glyph):
        for col, ch in enumerate(line):
            if ch == "#":
                bx = x + col * scale
                by = y + row * scale
                for dy in range(scale):
                    for dx in range(scale):
                        cv.set_pixel(bx + dx, by + dy, color)


# ---------------------------------------------------------------------------
# Drawing helpers
# ---------------------------------------------------------------------------

def draw_text(cv, text, x, y, color, scale=2):
    """Draw `text` left-aligned starting at (x, y), top-left of first glyph."""
    cx = x
    for ch in text:
        glyph = GLYPHS.get(ch)
        if glyph is not None:
            _draw_glyph(cv, glyph, cx, y, color, scale)
        cx += 6 * scale


def draw_text_center(cv, text, cx, y, color, scale=2):
    """Draw `text` horizontally centred on cx at top y."""
    x = cx - text_width(text, scale) // 2
    draw_text(cv, text, x, y, color, scale)


def draw_text_right(cv, text, x, y, color, scale=2):
    """Draw `text` right-aligned so it ends at x at top y."""
    x0 = x - text_width(text, scale)
    draw_text(cv, text, x0, y, color, scale)


# ---------------------------------------------------------------------------
# Text layout
# ---------------------------------------------------------------------------

def wrap_text(text, max_chars):
    """Greedy word-boundary wrap: lines of at most max_chars characters.

    A single word longer than max_chars is placed on its own line
    (overflow is the caller's problem to avoid by rewriting).
    """
    words = text.split()
    lines = []
    cur = ""
    for w in words:
        if not cur:
            cur = w
        elif len(cur) + 1 + len(w) <= max_chars:
            cur += " " + w
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


